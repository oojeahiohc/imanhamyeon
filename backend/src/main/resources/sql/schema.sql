CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id VARCHAR(20) UNIQUE,
    password_hash VARCHAR(255),
    auth_provider VARCHAR(10) NOT NULL,
    google_sub VARCHAR(255) UNIQUE,
    privacy_agreed_at TIMESTAMPTZ NOT NULL,
    ai_agreed_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT members_auth_provider_check CHECK (
        (auth_provider = 'LOCAL'
         AND login_id IS NOT NULL
         AND password_hash IS NOT NULL
         AND google_sub IS NULL)
        OR
        (auth_provider = 'GOOGLE'
         AND login_id IS NULL
         AND password_hash IS NULL
         AND google_sub IS NOT NULL)
    )
);
CREATE TABLE daily_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    goal_date DATE NOT NULL,
    concern_text TEXT NOT NULL,
    status VARCHAR(24) NOT NULL
        CHECK (status IN ('CHOICE_PENDING', 'NOT_COMPLETED',
                         'PARTIALLY_COMPLETED', 'ALL_COMPLETED')),
    selected_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT daily_records_member_date_unique UNIQUE (member_id, goal_date)
);

CREATE TABLE proposed_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    daily_record_id BIGINT NOT NULL
        REFERENCES daily_records(id) ON DELETE CASCADE,
    position SMALLINT NOT NULL CHECK (position BETWEEN 1 AND 3),
    title VARCHAR(100) NOT NULL,
    action_text VARCHAR(500) NOT NULL,
    is_selected BOOLEAN NOT NULL DEFAULT FALSE,
    is_completed BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT proposed_goals_position_unique
        UNIQUE (daily_record_id, position),
    CONSTRAINT proposed_goals_completion_check
        CHECK (NOT is_completed OR is_selected)
);

CREATE TABLE generation_guards (
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    goal_date DATE NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    succeeded_at TIMESTAMPTZ,
    PRIMARY KEY (member_id, goal_date)
);

CREATE TABLE api_usage_daily (
    usage_date DATE PRIMARY KEY,
    request_count INTEGER NOT NULL DEFAULT 0 CHECK (request_count >= 0),
    used_tokens BIGINT NOT NULL DEFAULT 0 CHECK (used_tokens >= 0),
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX daily_records_member_date_desc
    ON daily_records(member_id, goal_date DESC);